use crate::malware_engine::MalwareEngine;
use crate::syntax::SyntaxNode;
use crate::ir::IrBuilder;

/// The core execution engine for Meldor.
pub struct Engine {
    pub malware_engine: MalwareEngine,
    pub builder: IrBuilder,
}

impl Engine {
    pub fn new(malware_engine: MalwareEngine, builder: IrBuilder) -> Self {
        Engine {
            malware_engine,
            builder,
        }
    }

    /// Performs semantic analysis and prepares the execution plan.
    pub fn analyze_and_plan(&mut self, ast_root: &SyntaxNode) -> Result<(), String> {
        self.builder.log_event(&format!("Engine: Starting semantic analysis on AST root."));
        // In a real implementation, this would involve deep traversal and type checking.
        // For now, we simulate interaction with the malware engine.
        self.malware_engine.check_for_risks(ast_root);
        self.builder.log_event(&format!("Engine: Semantic analysis complete. Plan ready."));
        Ok(())
    }

    /// Executes the compiled/analyzed plan.
    pub fn execute(&mut self, ast_root: &SyntaxNode) -> Result<(), String> {
        self.builder.log_event(&format!("Engine: Starting execution phase."));
        // This is where the runtime loop would take over, using the IR generated by the builder.
        // We delegate the actual execution simulation to the malware engine for now.
        self.malware_engine.run_sandboxed_execution(ast_root);
        self.builder.log_event(&format!("Engine: Execution finished successfully."));
        Ok(())
    }
}
